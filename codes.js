export function calculateMagicWord(keys) {
  if (keys.length !== codeMaps.length) {
    throw new Error("Exactly three input codes are required.");
  }

  let total = keys.reduce((sum, key, index) => {
    const entry = codeMaps[index].find(([candidate]) => candidate === key);
    if (!entry) throw new Error(`Unknown code in column ${index + 1}: ${key}`);
    return sum + entry[1];
  }, 0);

  while (total >= 10000) total -= 9000;
  return total;
}

export function formatCode(value) {
  return value.toString().padStart(4, "0");
}
